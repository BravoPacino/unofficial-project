// 从 Masterplan.jsx 里那张总平面图 SVG（照开发商手册第 5 页描的，516 × 789，北在上）抽出几何，写成 src/data/sitePlan.js，
// 给一镜到底的世界（src/ink/site.js）用。SVG 改了就重跑：node tools/ink/site-extract.cjs
const fs = require('fs'), path = require('path')
const root = path.join(__dirname, '..', '..')
const src = fs.readFileSync(path.join(root, 'src/components/Masterplan.jsx'), 'utf8')
const at = src.indexOf('viewBox="0 0 516 789"'), i = src.lastIndexOf('<svg', at), j = src.indexOf('</svg>', at)
const svg = src.slice(i, j)
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]))
const out = { lines: [], paths: [], rects: [], circles: [] }
const stack = []
for (const m of svg.matchAll(/<(\/?)(\w+)([^>]*?)(\/?)>/g)) {
  const [, close, tag, body, self] = m
  if (tag === 'g') { if (close) stack.pop(); else stack.push(attrs(body).id || stack.at(-1) || null); continue }
  if (close || tag === 'svg' || tag === 'mask' || tag === 'defs' || tag === 'filter') continue
  const a = attrs(body), g = stack.at(-1) || null
  const st = { stroke: a.stroke || null, fill: a.fill || null }
  if (tag === 'line') out.lines.push([+a.x1, +a.y1, +a.x2, +a.y2, g])
  else if (tag === 'path') out.paths.push({ d: a.d, g, ...st })
  else if (tag === 'rect') out.rects.push([+(a.x || 0), +(a.y || 0), +a.width, +a.height, g, a.fill || null])
  else if (tag === 'circle') out.circles.push([+a.cx, +a.cy, +a.r, g])
  void self
}
const head = '// Generated by tools/ink/site-extract.cjs from the masterplan SVG in src/components/Masterplan.jsx (traced from the\n// developer\'s brochure, p. 5; 516 × 789 units, north up). Do not edit by hand: re-run the script.\n'
fs.writeFileSync(path.join(root, 'src/data/sitePlan.js'), head + 'export default ' + JSON.stringify(out) + '\n')
const by = {}
for (const l of out.lines) (by[l[4] || '-'] ||= { lines: 0, paths: 0 }).lines++
for (const p of out.paths) (by[p.g || '-'] ||= { lines: 0, paths: 0 }).paths++
console.log(JSON.stringify({ lines: out.lines.length, paths: out.paths.length, rects: out.rects.length, circles: out.circles.length }), JSON.stringify(by))
